import java.util.*;
public class relationOps {
    public static void main(String args[])
    {
        Scanner sc=new Scanner(System.in);
        System.out.println("Enter the first number: ");
        int a=sc.nextInt();
        System.out.println("Enter the second number: ");
        int b=sc.nextInt();
        System.out.println("case1:"+(a==b));
        System.out.println("case2:"+(a!=b));
        System.out.println("case3:"+(a>b));
        System.out.println("case4:"+(a<b));
        System.out.println("case5:"+(a>=b));
        System.out.println("case6:"+(a<=b));



    }

    
}

import java.util.*;
public class arithmetic {
    public static void main(String[] args)
    {
        Scanner sc= new Scanner(System.in);
        System.out.print("Enter the first no.: ");
        int a=sc.nextInt();
        System.out.print("Enteer the second no.: ");
        int b=sc.nextInt();
        System.out.println(a+b);
        System.out.println(a*b);
        System.out.println(a-b);
        System.out.println(a/b);
        System.out.println(a%b);
    }
    
}
